/** Address guests use on the marketing site. Booki reads mail sent here. */
export const BOOKING_INBOX = 'bookings@demorestaurant.co.za';

const msg = (id, from, text, time, extra = {}) => ({ id, from, text, time, ...extra });

function emailSummary(details) {
    return {
        name: details.name,
        phone: details.phone,
        date: details.dateIso,
        timeLabel: details.timeLabel,
        guests: details.guests,
        requests: details.requests === 'No special requests' ? 'no' : details.requests,
    };
}

const BOOKING_DETAILS_ASK = `To book a table, please reply with:
• Number of guests
• Date
• Time
• Name for the reservation
• Phone number
• Any special requests`;

/**
 * The guest only sends an enquiry. Booki asks for the booking details.
 * When the guest sends them, Booki confirms.
 */
function emailBookingThread(details) {
    const firstName = details.name.split(' ')[0];
    const messages = [
        msg('m1', 'customer', details.enquiry, details.guestTime),
        msg(
            'm2',
            'assistant',
            `Hello ${firstName},\n\nThanks for writing to ${BOOKING_INBOX}. I can help you book a table.\n\n${BOOKING_DETAILS_ASK}\n\nBooki`,
            details.botTime,
        ),
    ];
    if (!details.detailsTime) return messages;
    messages.push(msg(
        'm3',
        'customer',
        `Hello,\n\nHere are the details for the table:\n\nGuests: ${details.guests}\nDate: ${details.dateLabel}\nTime: ${details.timeLabel}\nName: ${details.name}\nPhone: ${details.phone}\nSpecial requests: ${details.requests}\n\nThank you,\n${details.name}`,
        details.detailsTime,
    ));
    messages.push(msg(
        'm4',
        'assistant',
        `Hello ${firstName},\n\nThank you. I have the details, and your table is confirmed below. This is a sample reply. No real reservation has been created.\n\nBooki`,
        details.confirmTime,
        { summary: emailSummary(details) },
    ));
    return messages;
}

function clockLabel(totalMinutes) {
    const h = Math.floor(totalMinutes / 60) % 24;
    const m = totalMinutes % 60;
    const suffix = h >= 12 ? 'PM' : 'AM';
    const hr = h % 12 || 12;
    return `${hr}:${String(m).padStart(2, '0')} ${suffix}`;
}

/** Spoken lines from the landing call demo, with this guest's answers. */
function widgetCallThread(details) {
    const lines = [
        ['assistant', 'Thank you for calling our restaurant. How may I help you?'],
        ['customer', `I'd like to reserve a table for ${details.guestsSpoken}.`],
        ['assistant', 'Certainly! What date would you like to visit?'],
        ['customer', details.dateLabel],
        ['assistant', 'Perfect. What name should I use for the reservation?'],
        ['customer', details.name],
        ['assistant', 'And the best number to send the confirmation to?'],
        ['customer', details.phone],
        ['assistant', `Wonderful. I'll hold a table for ${details.guestsSpoken} ${details.dateLabel.toLowerCase()}. You'll receive a sample summary after this call.`],
    ];
    return lines.map(([from, text], index) => msg(
        `m${index + 1}`,
        from,
        text,
        clockLabel(details.startMinute + index),
        index === lines.length - 1
            ? {
                summary: {
                    name: details.name,
                    phone: details.phone,
                    date: details.dateIso,
                    timeLabel: details.timeLabel,
                    guests: details.guests,
                    requests: details.requests === 'No special requests' ? 'no' : details.requests,
                },
            }
            : {},
    ));
}

