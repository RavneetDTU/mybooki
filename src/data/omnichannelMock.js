export function conversationPath(conversationId) {
    const item = MOCK_CONVERSATIONS.find((conversation) => conversation.id === conversationId);
    if (!item) return null;
    if (item.channel === 'phone') return '/all-calls';
    const page = CHANNEL_PAGES[item.channel];
    if (!page) return null;
    return `${page.path}?id=${item.id}`;
}

