/**
 * Map a known source string to a channel.
 * Unknown values (including manual and online) stay unmapped so we never invent a channel.
 */
export function resolveBookingSource(source) {
    if (!source) return null;
    const key = String(source).toLowerCase();
    if (key === 'whatsapp' || key === 'wa') return 'whatsapp';
    if (key === 'widget' || key === 'website_widget') return 'widget';
    if (key === 'email') return 'email';
    if (key === 'phone' || key === 'phone_call' || key === 'ai_call') return 'phone';
    return null;
}

